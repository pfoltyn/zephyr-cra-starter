"""hwsync: keep hardware.yaml, board files, the Renode twin and the build in sync.

  hwsync.py generate                 validate hardware.yaml and (re)write all generated files
  hwsync.py check                    validate and fail if any generated file is stale (CI)
  hwsync.py verify-build BUILD_DIR   compare the *built* devicetree with hardware.lock.yaml,
                                     catching overlays/Kconfig that silently moved a pin

Generated files are plain Zephyr/Renode sources and are committed, so the project
keeps building without this script (no lock-in).
"""

import argparse
import difflib
import hashlib
import pickle
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
GEN_HEADER = "GENERATED by scripts/hwsync.py from hardware.yaml. Do not edit; run `west hwsync generate`."

PIN_RE = re.compile(r"^P(\d)\.(\d\d)$")
NAME_RE = re.compile(r"^[a-z][a-z0-9_]*$")

BUS_ROLES = {
    "uart": {"required": ["tx", "rx"], "optional": ["rts", "cts"]},
    "i2c": {"required": ["sda", "scl"], "optional": []},
    "spi": {"required": ["sck", "mosi", "miso"], "optional": []},
}
INPUT_ROLES = {"rx", "cts", "miso"}
I2C_SPEEDS = {"standard": "I2C_BITRATE_STANDARD", "fast": "I2C_BITRATE_FAST"}


class HwError(Exception):
    pass


def load_yaml(path):
    with open(path) as f:
        return yaml.safe_load(f)


class Design:
    """hardware.yaml resolved against the SoC description and the block library."""

    def __init__(self, repo=REPO):
        self.repo = repo
        self.hw_path = repo / "hardware.yaml"
        self.hw = load_yaml(self.hw_path)
        self.board = self.hw["board"]
        self.soc = load_yaml(repo / "socs" / f"{self.board['soc']}.yaml")
        self.blocks = {}
        for blk in sorted((repo / "blocks").glob("*/block.yaml")):
            data = load_yaml(blk)
            self.blocks[data["id"]] = data
        self.errors = []
        self.warnings = []
        self.pins = {}  # "P0.06" -> {owner, function, direction}
        self._validate()

    # ------------------------------------------------------------------ validation

    def _err(self, msg):
        self.errors.append(msg)

    def _pin_ok(self, pin, where):
        m = PIN_RE.match(str(pin))
        if not m:
            self._err(f"{where}: '{pin}' is not a pin name (expected e.g. P0.06)")
            return False
        port, num = int(m.group(1)), int(m.group(2))
        width = self.soc["ports"].get(port)
        if width is None or num >= width:
            self._err(f"{where}: {pin} does not exist on {self.soc['soc']} package {self.soc['package']}")
            return False
        return True

    def _claim(self, pin, owner, function, direction):
        where = f"{owner} ({function})"
        if not self._pin_ok(pin, where):
            return
        special = self.soc.get("special_pins", {}).get(pin)
        if special:
            self._err(f"{where}: {pin} is the {special['function']} pin: {special['note']}")
        if pin in self.hw.get("reserved", {}):
            self._err(f"{where}: {pin} is reserved in hardware.yaml: {self.hw['reserved'][pin]}")
        if pin in self.pins:
            prev = self.pins[pin]
            self._err(f"{where}: {pin} already used by {prev['owner']} ({prev['function']})")
            return
        self.pins[pin] = {"owner": owner, "function": function, "direction": direction}

    def _validate(self):
        hw = self.hw
        if hw.get("schema") != 1:
            self._err("hardware.yaml: unsupported schema (expected `schema: 1`)")
        for key in ("name", "vendor"):
            if not NAME_RE.match(str(self.board.get(key, ""))):
                self._err(f"board.{key}: must match {NAME_RE.pattern}")

        for pin in hw.get("reserved", {}):
            self._pin_ok(pin, "reserved")

        periph = self.soc["peripherals"]
        used_instances = {}
        for bus, cfg in hw.get("buses", {}).items():
            if bus not in periph:
                self._err(f"buses.{bus}: no such peripheral on {self.soc['soc']}")
                continue
            p = periph[bus]
            roles = BUS_ROLES[p["type"]]
            for shared in p.get("shares", []):
                if shared in hw["buses"]:
                    self._err(f"buses.{bus}: shares a hardware instance with {shared}; use another instance")
            used_instances[bus] = p
            for role in roles["required"]:
                if role not in cfg:
                    self._err(f"buses.{bus}: missing required pin '{role}'")
            for role in roles["required"] + roles["optional"]:
                if role in cfg:
                    direction = "in" if role in INPUT_ROLES else ("bidir" if p["type"] == "i2c" else "out")
                    self._claim(cfg[role], bus, role.upper(), direction)
            extra = set(cfg) - set(roles["required"]) - set(roles["optional"]) - {"baudrate", "speed"}
            if extra:
                self._err(f"buses.{bus}: unknown keys {sorted(extra)}")
            if p["type"] == "i2c" and cfg.get("speed", "standard") not in I2C_SPEEDS:
                self._err(f"buses.{bus}: speed must be one of {sorted(I2C_SPEEDS)} on {self.soc['soc']}")
            if "renode" not in p:
                self.warnings.append(f"buses.{bus}: no Renode model, devices on this bus are NOT simulated")

        console = hw.get("console")
        if console and periph.get(console, {}).get("type") != "uart":
            self._err(f"console: '{console}' is not a configured UART")
        elif console and console not in hw.get("buses", {}):
            self._err(f"console: '{console}' is not listed under buses")

        self._check_evidence()
        allowlist = self._west_allowlist()
        addresses = {}
        for name, dev in hw.get("devices", {}).items():
            where = f"devices.{name}"
            if not NAME_RE.match(name):
                self._err(f"{where}: name must match {NAME_RE.pattern}")
            blk = self.blocks.get(dev.get("block"))
            if not blk:
                self._err(f"{where}: unknown block '{dev.get('block')}' (not in the supported menu; quote as new block work)")
                continue
            for mod in blk.get("west_modules", []):
                if allowlist is not None and mod not in allowlist:
                    self._err(f"{where}: block {blk['id']} needs west module '{mod}'; add it to the name-allowlist in west.yml")
            bus = dev.get("bus")
            bus_type = periph.get(bus, {}).get("type")
            if bus not in hw.get("buses", {}):
                self._err(f"{where}: bus '{bus}' is not configured under buses")
            elif blk["kind"] != f"{bus_type}-device":
                self._err(f"{where}: block {blk['id']} is a {blk['kind']}, but {bus} is {bus_type}")
            if blk["kind"] == "i2c-device":
                addr = dev.get("address")
                if addr not in blk["addresses"]:
                    allowed = ", ".join(hex(a) for a in blk["addresses"])
                    self._err(f"{where}: address {addr if addr is None else hex(addr)} not possible for {blk['id']} (straps allow {allowed})")
                key = (bus, addr)
                if key in addresses:
                    self._err(f"{where}: address {hex(addr)} on {bus} already used by {addresses[key]}")
                addresses[key] = name
            for sig, pin in dev.get("signals", {}).items():
                spec = blk.get("signals", {}).get(sig)
                if not spec:
                    self._err(f"{where}: block {blk['id']} has no signal '{sig}'")
                    continue
                self._claim(pin, name, sig.upper(), spec["direction"])
                if sig not in blk.get("renode", {}).get("signals", {}):
                    self.warnings.append(f"{where}.signals.{sig}: not wired in the twin (no model output); "
                                         "firmware paths using it are untested in simulation")

        for kind, items in (("leds", hw.get("leds", {})), ("buttons", hw.get("buttons", {}))):
            for name, cfg in items.items():
                if not NAME_RE.match(name):
                    self._err(f"{kind}.{name}: name must match {NAME_RE.pattern}")
                if cfg.get("active") not in ("low", "high"):
                    self._err(f"{kind}.{name}: active must be low or high")
                self._claim(cfg["pin"], f"{kind[:-1]}_{name}", kind[:-1].upper(), "out" if kind == "leds" else "in")

    def _used_blocks(self):
        used = {dev.get("block") for dev in self.hw.get("devices", {}).values()}
        if self.hw.get("leds"):
            used.add("gpio_led")
        if self.hw.get("buttons"):
            used.add("gpio_button")
        return sorted(b for b in used if b in self.blocks)

    def _check_evidence(self):
        """A block counts as validated only if the tests it cites exist."""
        for bid in self._used_blocks():
            refs = self.blocks[bid].get("validated_by", [])
            if not refs:
                self._err(f"block {bid}: no validated_by evidence (add a twin test)")
            for ref in refs:
                path, _, test = ref.partition("::")
                f = self.repo / path
                lines = f.read_text().splitlines() if f.exists() else []
                if test not in (ln.rstrip() for ln in lines):
                    self._err(f"block {bid}: evidence '{ref}' not found (test missing or renamed)")

    def _west_allowlist(self):
        manifest = self.repo / "west.yml"
        if not manifest.exists():
            return None
        for proj in load_yaml(manifest)["manifest"].get("projects", []):
            if proj.get("name") == "zephyr":
                return set(proj.get("import", {}).get("name-allowlist", [])) or None
        return None

    # ------------------------------------------------------------------ helpers

    @staticmethod
    def split_pin(pin):
        m = PIN_RE.match(pin)
        return int(m.group(1)), int(m.group(2))

    def gpio_ref(self, pin, flags):
        port, num = self.split_pin(pin)
        return f"&{self.soc['gpio_ports'][port]['dt']} {num} {flags}"

    def source_hash(self):
        return hashlib.sha256(self.hw_path.read_bytes()).hexdigest()[:16]

    @property
    def board_dir(self):
        return Path("boards") / self.board["vendor"] / self.board["name"]

    def used_ports(self):
        return sorted({self.split_pin(p)[0] for p in self.pins})

    # ------------------------------------------------------------------ renderers

    def render_pinctrl(self):
        out = [f"/* {GEN_HEADER} */", "", "&pinctrl {"]
        for bus, cfg in self.hw.get("buses", {}).items():
            p = self.soc["peripherals"][bus]
            roles = [r for r in BUS_ROLES[p["type"]]["required"] + BUS_ROLES[p["type"]]["optional"] if r in cfg]

            def psel(role):
                port, num = self.split_pin(cfg[role])
                return f"NRF_PSEL({p['psel'][role]}, {port}, {num})"

            outs = [r for r in roles if r not in INPUT_ROLES]
            ins = [r for r in roles if r in INPUT_ROLES]
            out.append(f"\t{bus}_default: {bus}_default {{")
            groups = [(outs, [])]
            if ins:
                groups.append((ins, ["bias-pull-up;"]))
            for i, (members, extra) in enumerate(groups, 1):
                out.append(f"\t\tgroup{i} {{")
                out.append("\t\t\tpsels = " + ",\n\t\t\t\t".join(f"<{psel(r)}>" for r in members) + ";")
                out.extend(f"\t\t\t{e}" for e in extra)
                out.append("\t\t};")
            out.append("\t};")
            out.append("")
            out.append(f"\t{bus}_sleep: {bus}_sleep {{")
            out.append("\t\tgroup1 {")
            out.append("\t\t\tpsels = " + ",\n\t\t\t\t".join(f"<{psel(r)}>" for r in roles) + ";")
            out.append("\t\t\tlow-power-enable;")
            out.append("\t\t};")
            out.append("\t};")
            out.append("")
        if out[-1] == "":
            out.pop()
        out.append("};")
        return "\n".join(out) + "\n"

    def render_hw_dtsi(self):
        hw = self.hw
        o = [f"/* {GEN_HEADER} */", "", "#include <zephyr/dt-bindings/input/input-event-codes.h>", "", "/ {"]
        if hw.get("console"):
            c = hw["console"]
            o += ["\tchosen {", f"\t\tzephyr,console = &{c};", f"\t\tzephyr,shell-uart = &{c};",
                  f"\t\tzephyr,uart-mcumgr = &{c};", "\t};", ""]
        aliases = []
        if hw.get("leds"):
            o += ["\tleds {", '\t\tcompatible = "gpio-leds";']
            for i, (name, cfg) in enumerate(hw["leds"].items()):
                flags = "GPIO_ACTIVE_LOW" if cfg["active"] == "low" else "GPIO_ACTIVE_HIGH"
                o += [f"\t\tled_{name}: led_{name} {{", f"\t\t\tgpios = <{self.gpio_ref(cfg['pin'], flags)}>;",
                      f'\t\t\tlabel = "{name}";', "\t\t};"]
                aliases.append((f"led{i}", f"led_{name}"))
            o += ["\t};", ""]
        if hw.get("buttons"):
            o += ["\tbuttons {", '\t\tcompatible = "gpio-keys";']
            for i, (name, cfg) in enumerate(hw["buttons"].items()):
                flags = "GPIO_ACTIVE_LOW" if cfg["active"] == "low" else "GPIO_ACTIVE_HIGH"
                pull = {"up": "GPIO_PULL_UP", "down": "GPIO_PULL_DOWN"}.get(cfg.get("pull"))
                flags = f"({pull} | {flags})" if pull else flags
                o += [f"\t\tbutton_{name}: button_{name} {{", f"\t\t\tgpios = <{self.gpio_ref(cfg['pin'], flags)}>;",
                      f'\t\t\tlabel = "{name}";', f"\t\t\tzephyr,code = <INPUT_KEY_{i}>;", "\t\t};"]
                aliases.append((f"sw{i}", f"button_{name}"))
            o += ["\t};", ""]
        for name in hw.get("devices", {}):
            aliases.append((name.replace("_", "-"), name))
        if aliases:
            o.append("\taliases {")
            o += [f"\t\t{a} = &{t};" for a, t in aliases]
            o.append("\t};")
        o += ["};", ""]

        for port in self.used_ports():
            o += [f"&{self.soc['gpio_ports'][port]['dt']} {{", '\tstatus = "okay";', "};", ""]
        o += ["&gpiote {", '\tstatus = "okay";', "};", ""]

        for bus, cfg in hw.get("buses", {}).items():
            p = self.soc["peripherals"][bus]
            o += [f"&{bus} {{"]
            if p.get("dt_compatible"):
                o.append(f'\tcompatible = "{p["dt_compatible"]}";')
            o.append('\tstatus = "okay";')
            if p["type"] == "uart":
                o.append(f"\tcurrent-speed = <{cfg.get('baudrate', 115200)}>;")
            if p["type"] == "i2c":
                o.append(f"\tclock-frequency = <{I2C_SPEEDS[cfg.get('speed', 'standard')]}>;")
            o += [f"\tpinctrl-0 = <&{bus}_default>;", f"\tpinctrl-1 = <&{bus}_sleep>;",
                  '\tpinctrl-names = "default", "sleep";']
            for name, dev in hw.get("devices", {}).items():
                if dev["bus"] != bus:
                    continue
                blk = self.blocks[dev["block"]]
                addr = dev["address"]
                o += ["", f"\t{name}: {blk['dt']['node_name']}@{addr:x} {{",
                      f'\t\tcompatible = "{blk["dt"]["compatible"]}";', f"\t\treg = <{addr:#04x}>;"]
                for sig, pin in dev.get("signals", {}).items():
                    spec = blk["signals"][sig]
                    o.append(f"\t\t{spec['dt_property']} = <{self.gpio_ref(pin, spec['dt_flags'])}>;")
                o.append("\t};")
            o += ["};", ""]
        while o[-1] == "":
            o.pop()
        return "\n".join(o) + "\n"

    def render_repl(self):
        hw = self.hw
        o = [f"// {GEN_HEADER}", f"// Twin of {self.board['full_name']} rev {self.board['revision']}.", "",
             f'using "{self.soc["renode_platform"]}"', ""]
        if self.soc.get("renode_overrides"):
            o += self.soc["renode_overrides"].rstrip("\n").splitlines() + [""]
        not_sim = []
        for name, dev in hw.get("devices", {}).items():
            blk = self.blocks[dev["block"]]
            bus_r = self.soc["peripherals"][dev["bus"]].get("renode")
            model = blk.get("renode", {}).get("model")
            if not bus_r or not model:
                not_sim.append(f"{name} ({blk['id']}): {'no bus model' if not bus_r else 'no device model'}")
                continue
            o.append(f"{name}: {model} @ {bus_r} {dev['address']:#04x}")
            for sig in dev.get("signals", {}):
                if sig not in blk.get("renode", {}).get("signals", {}):
                    not_sim.append(f"{name}.{sig}: signal not wired in the twin (model has no output for it)")
        o.append("")

        by_port = {}
        for name, cfg in hw.get("leds", {}).items():
            port, num = self.split_pin(cfg["pin"])
            by_port.setdefault(port, []).append((num, f"led_{name}"))
        for port, conns in sorted(by_port.items()):
            o.append(f"{self.soc['gpio_ports'][port]['renode']}:")
            o += [f"    {num} -> {target}@0" for num, target in conns]
            o.append("")
        for name, cfg in hw.get("leds", {}).items():
            port, num = self.split_pin(cfg["pin"])
            gp = self.soc["gpio_ports"][port]["renode"]
            o.append(f"led_{name}: Miscellaneous.LED @ {gp} {num}")
            if cfg["active"] == "low":
                o.append("    invert: true")
            o.append("")
        for name, cfg in hw.get("buttons", {}).items():
            port, num = self.split_pin(cfg["pin"])
            gp = self.soc["gpio_ports"][port]["renode"]
            o.append(f"button_{name}: Miscellaneous.Button @ {gp} {num}")
            if cfg["active"] == "low":
                o.append("    invert: true")
            o.append(f"    -> {gp}@{num}")
            o.append("")
        if not_sim:
            o.append("// NOT SIMULATED (shown in docs/hardware/pinout.md):")
            o += [f"//   {n}" for n in not_sim]
            o.append("")
        while o[-1] == "":
            o.pop()
        return "\n".join(o) + "\n"

    def render_lock(self):
        lock = {
            "board": f"{self.board['vendor']}/{self.board['name']}",
            "revision": self.board["revision"],
            "source_sha256": self.source_hash(),
            "pins": {p: self.pins[p] for p in sorted(self.pins, key=self.split_pin)},
            "devices": {},
        }
        for name, dev in self.hw.get("devices", {}).items():
            blk = self.blocks[dev["block"]]
            entry = {"block": blk["id"], "compatible": blk["dt"]["compatible"], "bus": dev["bus"]}
            if "address" in dev:
                entry["address"] = f"{dev['address']:#04x}"
            entry["simulated"] = bool(blk.get("renode")) and "renode" in self.soc["peripherals"][dev["bus"]]
            lock["devices"][name] = entry
        body = yaml.safe_dump(lock, sort_keys=False, default_flow_style=None, width=100)
        return f"# {GEN_HEADER}\n# Resolved pin/device assignment; reviewed by hardware (pins) and firmware (devicetree).\n{body}"

    def render_pinout(self):
        o = [f"<!-- {GEN_HEADER} -->", "", f"# {self.board['full_name']} (rev {self.board['revision']}): pinout", "",
             f"SoC: `{self.soc['soc']}` package `{self.soc['package']}`. Source: `hardware.yaml` "
             f"(sha256 `{self.source_hash()}`).", "",
             "| Pin | Function | Used by | Direction | Notes |", "|---|---|---|---|---|"]
        analog = self.soc.get("analog_pins", {})
        for pin in sorted(self.pins, key=self.split_pin):
            u = self.pins[pin]
            note = f"also {analog[pin]}" if pin in analog else ""
            o.append(f"| {pin} | {u['function']} | {u['owner']} | {u['direction']} | {note} |")
        for pin, sp in self.soc.get("special_pins", {}).items():
            o.append(f"| {pin} | {sp['function']} | *SoC* | | {sp['note']} |")
        for pin, why in self.hw.get("reserved", {}).items():
            o.append(f"| {pin} | *reserved* | | | {why} |")
        o += ["", "## Blocks", "", "| Device | Block | Bus / address | Simulated in twin | Reference circuit |",
              "|---|---|---|---|---|"]
        for name, dev in self.hw.get("devices", {}).items():
            blk = self.blocks[dev["block"]]
            sim = "yes" if blk.get("renode") and "renode" in self.soc["peripherals"][dev["bus"]] else "**no**"
            addr = f" @ {dev['address']:#04x}" if "address" in dev else ""
            ref = blk.get("provenance", {}).get("reference_circuit", "")
            o.append(f"| {name} | `{blk['id']}` | {dev['bus']}{addr} | {sim} | {ref} |")
        if self.warnings:
            o += ["", "## Not simulated", ""] + [f"- {w}" for w in self.warnings]
        if self.soc.get("twin_compromises"):
            o += ["", "## Twin compromises (SoC-level)", ""] + [f"- {c}" for c in self.soc["twin_compromises"]]
        return "\n".join(o) + "\n"

    def outputs(self):
        bd = self.board_dir
        name = self.board["name"]
        return {
            bd / f"{name}-pinctrl.dtsi": self.render_pinctrl(),
            bd / f"{name}-hw.dtsi": self.render_hw_dtsi(),
            Path("renode") / f"{name}.repl": self.render_repl(),
            Path("hardware.lock.yaml"): self.render_lock(),
            Path("docs/hardware/pinout.md"): self.render_pinout(),
        }


# ---------------------------------------------------------------------- verify-build

def _nrf_psel_decoder(zephyr_base):
    """Return f(psel_int) -> (function_name, 'Px.yy') using nrf-pinctrl.h from the Zephyr tree."""
    hdr = (Path(zephyr_base) / "include/zephyr/dt-bindings/pinctrl/nrf-pinctrl.h").read_text()
    defs = dict(re.findall(r"#define\s+(NRF_\w+)\s+(0x[0-9a-fA-F]+U?|\d+U?)\b", hdr))
    num = lambda k: int(defs[k].rstrip("U"), 0)
    fun_pos, fun_msk = num("NRF_FUN_POS"), num("NRF_FUN_MSK")
    pin_pos, pin_msk = num("NRF_PIN_POS"), num("NRF_PIN_MSK")
    funs = {num(k): k[len("NRF_FUN_"):] for k in defs if k.startswith("NRF_FUN_") and k not in ("NRF_FUN_POS", "NRF_FUN_MSK")}

    def decode(v):
        fun = funs.get((v >> fun_pos) & fun_msk, "?")
        pin = (v >> pin_pos) & pin_msk
        return fun, f"P{pin // 32}.{pin % 32:02d}"

    return decode


def verify_build(design, build_dir, zephyr_base):
    sys.path.insert(0, str(Path(zephyr_base) / "scripts/dts/python-devicetree/src"))
    pickles = [p for p in Path(build_dir).glob("**/zephyr/edt.pickle") if "mcuboot" not in p.parts]
    if not pickles:
        raise HwError(f"no edt.pickle under {build_dir} (build first)")
    problems = []
    decode = _nrf_psel_decoder(zephyr_base)
    # (owner, function) -> pin, as hardware.lock.yaml expects it
    expected = {(i["owner"], i["function"]): pin for pin, i in design.pins.items()}
    # devicetree property -> function name used in the lock file
    gpio_funcs = {"gpios": None}
    for dev in design.hw.get("devices", {}).values():
        for sig, spec in design.blocks[dev["block"]].get("signals", {}).items():
            gpio_funcs[spec["dt_property"]] = sig.upper()
    for pkl in pickles:
        with open(pkl, "rb") as f:
            edt = pickle.load(f)
        image = pkl.parent.parent.name
        actual = {}

        for node in edt.nodes:
            if node.status != "okay":
                continue
            label = node.labels[0] if node.labels else node.path
            for pc in node.pinctrls[:1]:  # default state only
                for conf in pc.conf_nodes:
                    for grp in conf.children.values():
                        for v in grp.props["psels"].val:
                            fun, pin = decode(v)
                            actual[(label, fun.rsplit("_", 1)[-1])] = pin
            for pname, prop in node.props.items():
                if not (pname.endswith("gpios") and prop.type == "phandle-array"):
                    continue
                for entry in prop.val:
                    ctrl = set(entry.controller.labels) if entry else set()
                    port = next((p for p, g in design.soc["gpio_ports"].items() if g["dt"] in ctrl), None)
                    if port is None:
                        continue
                    func = gpio_funcs.get(pname, pname)
                    if func is None:  # gpio-leds / gpio-keys children
                        func = "LED" if label.startswith("led_") else "BUTTON"
                    actual[(label, func)] = f"P{port}.{entry.data['pin']:02d}"

        for key in sorted(set(expected) | set(actual)):
            owner, func = key
            want, got = expected.get(key), actual.get(key)
            if want == got:
                continue
            if want and got:
                problems.append(f"{image}: {owner} {func}: hardware.lock.yaml says {want}, built devicetree says {got}")
            elif got:
                problems.append(f"{image}: {owner} {func} on {got} is not in hardware.yaml (added by an overlay?)")
            else:
                problems.append(f"{image}: {owner} {func} ({want}) is missing or disabled in the built devicetree")
        by_pin = {}
        for (owner, func), pin in actual.items():
            by_pin.setdefault(pin, []).append(f"{owner} {func}")
        for pin, users in sorted(by_pin.items()):
            if len(users) > 1:
                problems.append(f"{image}: {pin} is driven by several functions: {', '.join(users)}")

        for name, dev in design.hw.get("devices", {}).items():
            node = edt.label2node.get(name)
            blk = design.blocks[dev["block"]]
            if node is None or node.status != "okay":
                problems.append(f"{pkl.parent.parent.name}: device '{name}' missing or disabled in built devicetree")
                continue
            if blk["dt"]["compatible"] not in node.compats:
                problems.append(f"{name}: compatible {node.compats} != {blk['dt']['compatible']}")
            if "address" in dev and node.regs and node.regs[0].addr != dev["address"]:
                problems.append(f"{name}: address {node.regs[0].addr:#04x} in devicetree, "
                                f"{dev['address']:#04x} in hardware.yaml")
            parent = node.parent.labels[0] if node.parent.labels else node.parent.path
            if parent != dev["bus"]:
                problems.append(f"{name}: on {parent} in devicetree, on {dev['bus']} in hardware.yaml")
    return problems


# ---------------------------------------------------------------------- CLI

def report(design):
    for w in design.warnings:
        print(f"warning: {w}")
    if design.errors:
        for e in design.errors:
            print(f"error: {e}", file=sys.stderr)
        raise HwError(f"hardware.yaml has {len(design.errors)} error(s)")


def cmd_generate(design):
    report(design)
    for rel, content in design.outputs().items():
        path = design.repo / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text() != content:
            path.write_text(content)
            print(f"wrote {rel}")
    print("hardware.yaml OK, generated files up to date")


def cmd_check(design):
    report(design)
    stale = 0
    for rel, content in design.outputs().items():
        path = design.repo / rel
        current = path.read_text() if path.exists() else ""
        if current != content:
            stale += 1
            print(f"STALE: {rel}")
            sys.stdout.writelines(difflib.unified_diff(current.splitlines(True), content.splitlines(True),
                                                       f"a/{rel}", f"b/{rel}"))
    if stale:
        raise HwError(f"{stale} generated file(s) out of date or hand-edited; run `west hwsync generate`")
    print("hardware.yaml OK, generated files in sync")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("generate")
    sub.add_parser("check")
    vb = sub.add_parser("verify-build")
    vb.add_argument("build_dir")
    vb.add_argument("--zephyr-base", default=None)
    args = ap.parse_args(argv)
    try:
        design = Design()
        if args.cmd == "generate":
            cmd_generate(design)
        elif args.cmd == "check":
            cmd_check(design)
        else:
            import os
            zb = args.zephyr_base or os.environ.get("ZEPHYR_BASE") or str(REPO.parent / "zephyr")
            report(design)
            problems = verify_build(design, args.build_dir, zb)
            for p in problems:
                print(f"MISMATCH: {p}")
            if problems:
                raise HwError(f"{len(problems)} mismatch(es) between hardware.lock.yaml and the built devicetree")
            print("built devicetree matches hardware.lock.yaml")
    except HwError as e:
        print(f"hwsync: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
